/**
 * Обход серверного кэша Django.
 *
 * Несколько представлений в `medweb/medml/views.py` обёрнуты в
 * `@method_decorator(cache_page(60))` — в том числе список пациентов врача и
 * таблица снимков. Это изменяемые данные конкретного пользователя, и кэшировать
 * их на минуту нельзя: после создания пациента фронт честно перезапрашивает
 * список, а Django отдаёт ту же страницу из Redis, где нового пациента ещё нет.
 *
 * Правильное место для починки — бэкенд, там достаточно снять декоратор. Пока
 * это не сделано, обходим кэш со стороны клиента: `cache_page` строит ключ по
 * полному URL вместе со строкой запроса, поэтому достаточно добавить параметр,
 * который меняется после каждой правки данных.
 *
 * Счётчик модульный, а не в Redux, намеренно: он не влияет на отрисовку и не
 * должен вызывать перерендер. Значение подставляется в момент формирования
 * запроса — то есть при перезапросе, который инициирует инвалидация тегов.
 */

export type CacheBuster = {
	/** Текущее значение для строки запроса; `undefined`, пока данные не менялись. */
	value(): number | undefined
	/** Отметить, что данные изменились: следующий запрос пойдёт мимо кэша. */
	bump(): void
}

export function createCacheBuster(): CacheBuster {
	let current: number | undefined

	return {
		value: () => current,
		bump: () => {
			// Date.now() может совпасть при двух правках подряд в одну
			// миллисекунду — тогда ключ не изменится. Поэтому гарантируем рост.
			const next = Date.now()
			current = current != null && next <= current ? current + 1 : next
		},
	}
}
