/**
 * Базовые геометрические типы вьюеров.
 *
 * Лежат отдельно от `uzi-viewer/coords.ts`, чтобы модули измерений и кисти
 * не тянули за собой пакет `openseadragon`: точка на плоскости — это просто
 * пара чисел, и для неё движок не нужен.
 */

/** Точка на плоскости — в координатах снимка либо в координатах элемента. */
export interface PlanePoint {
	x: number
	y: number
}

/** Габариты прямоугольной области в пикселях. */
export interface PlaneSize {
	widthPx: number
	heightPx: number
}
